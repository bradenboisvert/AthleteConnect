import test from 'node:test';
import assert from 'node:assert/strict';
import { createApp } from '../server/index.js';
import { localFetch } from './transport.js';
test('complete workflow and server-side authorization', async t => {
  const { server, db } = createApp({ databasePath: ':memory:' });
  t.after(() => db.close());
  const origin = 'http://127.0.0.1:4173';
  const fetch = (input, options) => localFetch(server, input, options);
  async function request(path, method = 'GET', data, cookie = '', expected = 200) {
    const res = await fetch(origin + '/api' + path, { method, headers: { Origin: origin, ...(method === 'GET' ? {} : { 'Content-Type': 'application/json' }), Cookie: cookie }, body: method === 'GET' ? undefined : JSON.stringify(data || {}) });
    const result = await res.json(); assert.equal(res.status, expected, `${method} ${path}: ${JSON.stringify(result)}`);
    return { result, cookie: res.headers.get('set-cookie')?.split(';')[0] };
  }
  const register = async (email, role) => (await request('/auth/register', 'POST', { email, role, password: 'SecurePassword!2026' }, '', 201)).cookie;
  const player = await register('player@example.test', 'player');
  const coach = await register('coach@example.test', 'coach');
  const other = await register('other@example.test', 'player');
  const admin = await register('admin@example.test', 'player');
  const adminId = (await request('/me', 'GET', null, admin)).result.user.id;
  db.prepare("UPDATE users SET role='admin' WHERE id=?").run(adminId);
  const coachId = (await request('/me', 'GET', null, coach)).result.user.id;
  const pp = { fullName: 'Player Test', sport: 'Baseball', location: 'Utah', age: 16, skillLevel: 'Intermediate', sessionTypes: ['virtual'], goalsObjectives: 'Training', guardianConsent: true, parent: { name: 'Test Guardian', email: 'guardian@example.test', phone: '555-555-1212' } };
  await request('/profile', 'PUT', { ...pp, guardianConsent: false }, player, 400);
  await request('/profile', 'PUT', pp, player);
  await request('/profile', 'PUT', { ...pp, fullName: 'Other Player', age: 20 }, other);
  const cp = { fullName: 'Coach Test', sport: 'Baseball', location: 'Utah', bio: 'A sufficiently detailed and specific coaching biography for testing.', credentials: 'Demo coaching experience', hourlyRate: 65, sessionTypes: ['virtual'], acceptingBookings: true, status: 'approved', role: 'admin' };
  await request('/profile', 'PUT', cp, coach);
  assert.equal((await request('/me', 'GET', null, coach)).result.user.profile.status, 'pending');
  assert.equal((await request('/coaches', 'GET', null, player)).result.coaches.length, 0);
  const startTime = Date.now() + 86400000;
  await request('/slots', 'POST', { startTime, duration: 60, type: 'virtual' }, coach, 403);
  await request(`/admin/coaches/${coachId}`, 'POST', { status: 'approved' }, player, 403);
  await request(`/admin/coaches/${coachId}`, 'POST', { status: 'approved' }, admin);
  await request('/slots', 'POST', { startTime, duration: 60, type: 'virtual' }, coach, 201);
  await request('/slots', 'POST', { startTime: startTime + 1000, duration: 60, type: 'virtual' }, coach, 409);
  const slot = (await request(`/slots?coachId=${coachId}`, 'GET', null, player)).result.slots[0];
  const sessionId = (await request('/sessions', 'POST', { slotId: slot.id, price: 0, coachId: 'spoofed', playerIsMinor: false }, player, 201)).result.id;
  const otherRequest = (await request('/sessions', 'POST', { slotId: slot.id }, other, 201)).result.id;
  const s = (await request('/sessions', 'GET', null, player)).result.sessions[0];
  assert.equal(s.price, 65); assert.equal(s.playerIsMinor, true); assert.equal(s.coachId, coachId);
  await request(`/sessions/${sessionId}/accept`, 'POST', {}, player, 403);
  await request(`/sessions/${sessionId}/accept`, 'POST', {}, coach);
  await request(`/sessions/${otherRequest}/accept`, 'POST', {}, coach, 400);
  await request(`/sessions/${sessionId}/messages`, 'GET', null, other, 404);
  await request(`/sessions/${sessionId}/cancel`, 'POST', {}, other, 404);
  await request(`/sessions/${sessionId}/messages`, 'POST', { text: 'Intrusion' }, other, 404);
  await request(`/sessions/${sessionId}/messages`, 'GET', null, admin, 404);
  await request(`/sessions/${sessionId}/messages`, 'POST', { text: 'Hello <script>alert(1)</script>' }, player, 201);
  assert.equal((await request(`/sessions/${sessionId}/messages`, 'GET', null, coach)).result.messages[0].text, 'Hello <script>alert(1)</script>');
  await request(`/sessions/${sessionId}/meeting`, 'POST', { meetLink: 'https://meet.google.com/abc-defg-hij' }, player, 403);
  await request(`/sessions/${sessionId}/meeting`, 'POST', { meetLink: 'javascript:alert(1)' }, coach, 400);
  await request(`/sessions/${sessionId}/meeting`, 'POST', { meetLink: 'https://meet.google.com/abc-defg-hij' }, coach);
  const exported = await fetch(origin + `/api/sessions/${sessionId}/calendar`, { headers: { Cookie: player } }); assert.equal(exported.status, 200); assert.match(await exported.text(), /BEGIN:VCALENDAR/);
  await request('/admin/people', 'GET', null, player, 403);
  await request('/profile', 'PUT', { ...cp, bio: cp.bio + ' Updated.' }, coach);
  assert.equal((await request('/me', 'GET', null, coach)).result.user.profile.status, 'pending');
  await request('/photo', 'PUT', { mime: 'image/png', base64: Buffer.from('<script>bad</script>').toString('base64') }, player, 400);
  const csrf = await fetch(origin + '/api/auth/logout', { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: 'https://evil.test', Cookie: player }, body: '{}' }); assert.equal(csrf.status, 403);
  await request('/auth/logout', 'POST', {}, player);
  assert.equal((await request('/me', 'GET', null, player)).result.user, null);
  await request('/sessions', 'GET', null, player, 401);
  await request('/auth/login', 'POST', { email: 'player@example.test', password: 'IncorrectPassword' }, '', 401);
  const fresh = await request('/auth/login', 'POST', { email: 'player@example.test', password: 'SecurePassword!2026' });
  assert.ok(fresh.cookie.includes('ac_session='));
  await request('/sessions', 'GET', null, fresh.cookie);
  const manifest = await fetch(origin + '/manifest.webmanifest'); assert.equal(manifest.status, 200); assert.equal((await manifest.json()).display, 'standalone');
  const traversal = await fetch(origin + '/src/../server/index.js'); assert.equal(traversal.status, 404);
});
